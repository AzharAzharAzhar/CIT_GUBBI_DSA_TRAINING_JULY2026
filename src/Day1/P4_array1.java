package Day1;
public class P4_array1 {
    public static void main(String[] args) {
        int[] a = new int[2];
        int b[] = {12,13,14,15,16};
        a[0] = 12;
        a[1] = 13;
        for(int i:a){
            System.out.print(i);
        }
        for(int i:b){
            System.out.print(i);
        }
    }
}
